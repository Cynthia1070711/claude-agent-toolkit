#!/usr/bin/env node
/**
 * Template B — PostToolUse context injection
 *
 * Use when you want to remind Claude AFTER a write/edit happened.
 * Does NOT block the action. Injects additionalContext that Claude reads on next turn.
 *
 * settings.json registration:
 *   "PostToolUse": [{
 *     "matcher": "Edit|Write",
 *     "hooks": [{
 *       "type": "command",
 *       "command": "cd \"$CLAUDE_PROJECT_DIR\" && node .claude/hooks/template-b-post-tool-warn.js",
 *       "timeout": 3000
 *     }]
 *   }]
 *
 * Key rule for additionalContext text:
 *   Write FACTUAL STATEMENTS, not commands.
 *   GOOD: "This file is generated by codegen.ts."
 *   BAD:  "DO NOT edit this file directly!"
 */

const fs = require('fs');
const path = require('path');

const RULES = [
  {
    test: (filePath) => /generated[\\/].+\.(ts|js|cs)$/i.test(filePath),
    note: (filePath) => `${filePath} is a generated artifact. Source of truth is the corresponding template/schema, not this file.`,
  },
  {
    test: (filePath) => /[\\/]docs[\\/]idd[\\/].*\.md$/i.test(filePath),
    note: (filePath) => `${filePath} is an IDD doc. Per IDD-COM-001, free-tier feature toggles must remain open; verify the change does not silently gate features behind paywalls.`,
  },
  {
    test: (filePath) => /[\\/]appsettings\..*\.json$/i.test(filePath),
    note: (filePath) => `${filePath} is environment config. Verify no secrets were inlined; secrets belong in Azure Key Vault or .env (not committed).`,
  },
];

(async () => {
  let raw = '';
  for await (const c of process.stdin) raw += c;

  let data;
  try { data = JSON.parse(raw); } catch { process.exit(0); }

  const filePath = data.tool_input?.file_path;
  if (!filePath) process.exit(0);

  const notes = [];
  for (const rule of RULES) {
    if (rule.test(filePath)) notes.push(rule.note(filePath));
  }

  if (notes.length === 0) process.exit(0);

  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PostToolUse',
      additionalContext: notes.join('\n'),
    }
  }));
  process.exit(0);
})().catch(err => {
  process.stderr.write(`[post-tool-warn] ${err.message}\n`);
  process.exit(0);
});